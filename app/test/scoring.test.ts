import assert from 'node:assert/strict';
import { predict, type Model } from '../src/lib/gbm';
import { scorePitch, stuffEstable } from '../src/lib/scoring';
import { solveRelease, releaseAt, dragIndexAtAltitude, type PitchInput } from '../src/lib/physics';
import { rpmSensitivity } from '../src/lib/sensitivity';
import modelJson from '../public/data/model_stuff.json';
import helpers from '../public/data/helpers.json';
import scale from '../public/data/scale.json';
const model = modelJson as unknown as Model;
const base: PitchInput = { relSpeed: 92.4, ivb: 15.7, hb: 8, spinRate: 2300, relHeight: 5.9, relSide: 1.6, extension: 6.1, plateZ: 2.9, plateX: 0 };
const near = (x: number, y: number, tolerance = 1e-8) => assert.ok(Math.abs(x - y) < tolerance, `${x} differs from ${y}`);
const rel = solveRelease(base);
const sea = scorePitch(base, 1, true, model, helpers, scale.stuff, rel);
const air = dragIndexAtAltitude(2240);
const alt = scorePitch(base, air, true, model, helpers, scale.stuff, rel);
for (const name of ['RelSpeed', 'EffectiveVelo', 'SpinRate', 'SpinAxis', 'RelHeight', 'RelSide', 'Extension', 'VertRelAngle', 'HorzRelAngle', 'is_rhp']) near(sea.features[name], alt.features[name]);
near(alt.features.VertBreak - sea.features.VertBreak, alt.features.InducedVertBreak - sea.features.InducedVertBreak);
near(alt.features.spin_efficiency / sea.features.spin_efficiency, alt.features.movement_total / sea.features.movement_total);
assert.ok(alt.features.SpeedDrop < sea.features.SpeedDrop, 'Thinner air reduces speed loss');
assert.ok(alt.features.ZoneSpeed > sea.features.ZoneSpeed, 'Thinner air increases plate speed');
assert.ok(alt.features.movement_total < sea.features.movement_total, 'Thinner air reduces preset movement');
const identity = stuffEstable(base, [1, 1], true, model, helpers, scale.stuff);
near(identity[0], identity[1]);
assert.deepEqual(identity, stuffEstable(base, [1, 1], true, model, helpers, scale.stuff), 'Smoothing is deterministic');
const mirrored = releaseAt(solveRelease({ ...base, hb: -base.hb, relSide: -base.relSide, plateX: -base.plateX }), air);
near(mirrored.shape.hb, -alt.traj.shape.hb, .01);
near(mirrored.shape.plateZ, alt.traj.shape.plateZ, .001);
for (const p of [base, { ...base, relSpeed: 78.5, ivb: -8, hb: -9.5 }, { ...base, relSpeed: 70, ivb: 24, hb: -22, plateZ: .8 }]) assert.ok(stuffEstable(p, [1, .8534], true, model, helpers, scale.stuff).every(Number.isFinite));
const constant: Model = { features: [], objective: 'regression', trees: [{ f: [], t: [], l: [], r: [], d: [], v: [2.5] }] };
near(predict(constant, {}), 2.5);
const missing: Model = { features: ['a'], objective: 'regression', trees: [{ f: [0], t: [1], l: [-1], r: [-2], d: [1], v: [3, 5] }] };
near(predict(missing, {}), 3); near(predict(missing, { a: 2 }), 5);
const cancellation = rpmSensitivity([{ rpm: 1900, mar: 100 }, { rpm: 2000, mar: 104 }, { rpm: 2100, mar: 100 }])!;
near(cancellation.endpointPer100, 0); near(cancellation.meanAbsolutePer100, 4);
assert.equal(rpmSensitivity([]), null);
assert.throws(() => rpmSensitivity([{ rpm: 2000, mar: 100 }, { rpm: 2000, mar: 101 }]));
console.log('PASS: feature transfer, thinner air, identity, determinism, handedness, finite controls, constant/missing trees, nonlinear sensitivity');
